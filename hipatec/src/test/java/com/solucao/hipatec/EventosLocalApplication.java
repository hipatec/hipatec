package com.solucao.hipatec;

import java.nio.file.*;
import java.sql.*;
import org.springframework.boot.SpringApplication;
import org.springframework.security.crypto.bcrypt.BCryptPasswordEncoder;

/** Somente teste local: banco H2 em arquivo, sem integrações externas ou dados reais. */
public class EventosLocalApplication {
    public static void main(String[] args) throws Exception {
        if (args.length < 2) throw new IllegalArgumentException("preparar|servir|verificar caminho-absoluto-banco [migração|porta]");
        Path banco = Path.of(args[1]).toAbsolutePath().normalize();
        if (!banco.startsWith("/home/rosa/.hermes/cache/scratch/")) throw new IllegalArgumentException("Use somente scratch.");
        String url = "jdbc:h2:file:" + banco + ";MODE=PostgreSQL;DB_CLOSE_ON_EXIT=FALSE";
        if (args[0].equals("preparar")) {
            if (Files.exists(Path.of(banco + ".mv.db"))) throw new IllegalStateException("Banco já existe; preparação não pode sobrescrever dados.");
            Files.createDirectories(banco.getParent());
            try (var c = DriverManager.getConnection(url, "sa", ""); var sql = c.createStatement()) {
                // Estado legado sintético mínimo, anterior à migração. Nenhum ddl-auto é utilizado.
                sql.execute("CREATE TABLE estudante(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(255), email VARCHAR(255) UNIQUE, senha VARCHAR(255), data_nascimento DATE)");
                sql.execute("CREATE TABLE mentora(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(255), email VARCHAR(255) UNIQUE, senha VARCHAR(255), data_nascimento DATE, aprovada BOOLEAN)");
                sql.execute("CREATE TABLE perfil(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, biografia VARCHAR(255), num_seguidores INTEGER DEFAULT 0, num_seguindo INTEGER DEFAULT 0, num_publicacoes INTEGER DEFAULT 0, usuario VARCHAR(255), pfp VARCHAR(255), background VARCHAR(255), id_estudante INTEGER, id_mentora INTEGER)");
                sql.execute("CREATE TABLE seguimento(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, seguidor_perfil_id INTEGER, seguido_perfil_id INTEGER, criado_em TIMESTAMP)");
                sql.execute("CREATE TABLE mentoria(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, titulo VARCHAR(255), descricao VARCHAR(255), progresso FLOAT, id_mentora INTEGER)");
                sql.execute("CREATE TABLE evento_mentoria(id BIGINT PRIMARY KEY, mentoria_id INTEGER NOT NULL REFERENCES mentoria(id), titulo VARCHAR(255), inicio TIMESTAMP)");
                sql.execute("INSERT INTO mentoria(id,titulo) VALUES(1,'Mentoria anterior sintética')");
                sql.execute("INSERT INTO evento_mentoria VALUES(1,1,'Agenda anterior',TIMESTAMP '2026-11-01 10:00:00')");
                String hash = "{bcrypt}" + new BCryptPasswordEncoder(4).encode("TesteLocal123!");
                for (String nome : new String[]{"aluna", "outra"}) {
                    try (var insert = c.prepareStatement("INSERT INTO estudante(nome,email,senha) VALUES(?,?,?)")) {
                        insert.setString(1,nome); insert.setString(2,nome+"@example.test"); insert.setString(3,hash); insert.executeUpdate();
                    }
                }
                for (String nome : new String[]{"mentora", "pendente"}) {
                    try (var insert = c.prepareStatement("INSERT INTO mentora(nome,email,senha,aprovada) VALUES(?,?,?,?)")) {
                        insert.setString(1,nome); insert.setString(2,nome+"@example.test"); insert.setString(3,hash); insert.setBoolean(4,nome.equals("mentora")); insert.executeUpdate();
                    }
                }
                sql.execute("INSERT INTO perfil(usuario,id_estudante) VALUES('aluna',1),('outra',2)");
                sql.execute("INSERT INTO perfil(usuario,id_mentora) VALUES('mentora',1),('pendente',2)");
                // Aplica os bytes da migração versionada, sem reescrever o script anterior.
                String migracao = Files.readString(Path.of(args[2]));
                for (String comando : migracao.replaceAll("(?m)--.*$", "").split(";")) if (!comando.isBlank()) sql.execute(comando);
            }
            System.out.println("PASS preparação legada + migração aditiva");
        } else if (args[0].equals("verificar")) {
            try (var c = DriverManager.getConnection(url, "sa", ""); var s = c.createStatement()) {
                for (String consulta : new String[]{"SELECT COUNT(*) FROM evento_mentoria WHERE id=1 AND mentoria_id=1 AND titulo='Agenda anterior'", "SELECT COUNT(*) FROM estudante WHERE email='aluna@example.test'", "SELECT COUNT(*) FROM evento"}) {
                    try (var resultado = s.executeQuery(consulta)) {
                        resultado.next(); if (resultado.getInt(1) < 1) throw new AssertionError("Permanência não comprovada");
                    }
                }
            }
            System.out.println("PASS dados anteriores + eventos permanecem em novo processo");
        } else if (args[0].equals("servir")) {
            servir(banco, args[2]);
        } else throw new IllegalArgumentException("Modo desconhecido");
    }

    static org.springframework.context.ConfigurableApplicationContext servir(Path banco, String porta) throws Exception {
        String url = "jdbc:h2:file:" + banco + ";MODE=PostgreSQL;DB_CLOSE_ON_EXIT=FALSE";
        var context = new SpringApplication(EventosTests.Config.class).run(
                "--spring.config.location=optional:classpath:/application-eventos-local.properties",
                "--spring.datasource.url=" + url, "--spring.datasource.username=sa", "--spring.datasource.password=",
                "--spring.datasource.driver-class-name=org.h2.Driver", "--spring.jpa.hibernate.ddl-auto=none",
                "--server.address=127.0.0.1", "--server.port=" + porta,
                "--server.servlet.session.cookie.secure=false", "--server.servlet.session.cookie.same-site=lax",
                "--hipatec.firebase.enabled=false", "--hipatec.posts.enabled=false");
        try {
            SocialLocalFixture.configurar(context);
            System.out.println("TEST: feed e interações são fixtures sintéticas em memória; eventos usam H2 arquivo. Posts antigos não são restaurados.");
            return context;
        } catch (Exception e) {
            context.close();
            throw e;
        }
    }
}
