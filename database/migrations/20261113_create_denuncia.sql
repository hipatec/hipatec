BEGIN;
CREATE TABLE denuncia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    perfil_id INTEGER NOT NULL REFERENCES perfil(id),
    post_id VARCHAR(150) NOT NULL,
    comentario_id VARCHAR(150) NOT NULL DEFAULT '',
    motivo VARCHAR(40) NOT NULL CHECK(motivo IN ('assedio','discurso-odioso','spam','conteudo-inadequado')),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE' CHECK(status IN ('PENDENTE','ANALISADA')),
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_denuncia_pessoa_alvo UNIQUE(perfil_id,post_id,comentario_id)
);
CREATE INDEX ix_denuncia_fila ON denuncia(status,criado_em);
COMMIT;
