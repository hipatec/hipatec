-- Não altera EventoMentoria nem registros anteriores. Falha se a tabela já existe: não mascara drift.
BEGIN;
CREATE TABLE evento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proprietario_perfil_id INTEGER NOT NULL REFERENCES perfil(id),
    requisicao_id VARCHAR(36) NOT NULL,
    titulo VARCHAR(160) NOT NULL CHECK (CHAR_LENGTH(TRIM(titulo)) > 0),
    data DATE NOT NULL CHECK (data BETWEEN DATE '2000-01-01' AND DATE '2100-12-31'),
    horario TIME NULL,
    local VARCHAR(1000) NOT NULL,
    descricao VARCHAR(4000) NOT NULL,
    visibilidade VARCHAR(10) NOT NULL CHECK (visibilidade IN ('PRIVADO', 'PUBLICO')),
    fuso VARCHAR(40) NOT NULL CHECK (fuso = 'America/Sao_Paulo'),
    CONSTRAINT uk_evento_dono_requisicao UNIQUE (proprietario_perfil_id, requisicao_id)
);
CREATE INDEX ix_evento_dono_data ON evento(proprietario_perfil_id, data);
CREATE INDEX ix_evento_visibilidade_data ON evento(visibilidade, data);
COMMIT;
